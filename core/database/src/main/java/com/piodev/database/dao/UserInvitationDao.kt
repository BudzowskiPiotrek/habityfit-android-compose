package com.piodev.database.dao

import androidx.room.Dao
import androidx.room.Query
import com.piodev.database.entities.UserInvitationEntity

@Dao
interface UserInvitationDao : BaseDao<UserInvitationEntity> {
    ////////////////////////////////////////////////////////////////////////////////////////////////
    // LECTURA
    ////////////////////////////////////////////////////////////////////////////////////////////////

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // ESCRITURA
    ////////////////////////////////////////////////////////////////////////////////////////////////

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // SINCRONIZACIÓN
    ////////////////////////////////////////////////////////////////////////////////////////////////
    @Query("SELECT * FROM USER_INVITATION WHERE SYNC_STATUS = 'PENDING'")
    suspend fun getPendingSync(): List<UserInvitationEntity>

    @Query("UPDATE USER_INVITATION SET SYNC_STATUS = 'SYNCED' WHERE ID IN (:ids)")
    suspend fun markAsSynced(ids: List<String>)
    ////////////////////////////////////////////////////////////////////////////////////////////////
    // SOFT DELETE
    ////////////////////////////////////////////////////////////////////////////////////////////////
    @Query("UPDATE USER_INVITATION SET DELETED_AT = :date, SYNC_STATUS = 'PENDING' WHERE ID = :id")
    suspend fun softDeleteById(id: String, date: Long)
}