package com.piodev.habityfit.features.community.domain.repository

import com.piodev.habityfit.features.community.domain.model.UserRelations
import kotlinx.coroutines.flow.Flow

interface FriendsRepository {
    ////////////////////////////////////////////////////////////////////////////////////////////////
    // LECTURA
    ////////////////////////////////////////////////////////////////////////////////////////////////
    fun getFriends(userId: String): Flow<List<UserRelations>>
    fun getPendingRequests(userId: String): Flow<List<UserRelations>>

    fun getSentRequests(userId: String): Flow<List<UserRelations>>

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // ENVIO
    ////////////////////////////////////////////////////////////////////////////////////////////////
    suspend fun sendFriendRequest(friendCode: String, userId: String): Result<Unit>

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // ESCRITURA
    ////////////////////////////////////////////////////////////////////////////////////////////////
    suspend fun acceptFriendRequest(relationId: String): Result<Unit>
    suspend fun declineFriendRequest(relationId: String): Result<Unit>
    suspend fun sendInvitation(email: String, senderId: String): Result<Unit>
}