package com.piodev.habityfit.features.auth.domain.repository

import com.piodev.habityfit.features.auth.domain.model.User
import kotlinx.coroutines.flow.Flow

interface AuthRepository {
    ////////////////////////////////////////////////////////////////////////////////////////////////
    // LOGIN Y LOGOUT
    ////////////////////////////////////////////////////////////////////////////////////////////////
    suspend fun login(email: String, password: String): Result<User>
    suspend fun accept(token: String, fullName: String, password: String): Result<User>
    suspend fun logout()
    suspend fun acceptTerms(userId: String): Result<Unit>

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // OBTENER USUARIO
    ////////////////////////////////////////////////////////////////////////////////////////////////
    fun getCurrentUser(): Flow<User?>

    ////////////////////////////////////////////////////////////////////////////////////////////////
    // REGISTRO
    ////////////////////////////////////////////////////////////////////////////////////////////////
    suspend fun register(email: String): Result<Unit>
}